"""Round 10 (D144 / D145) — build and check the Science version (manuscript/science).

1  Numbering of the Supplementary figures by first citation: main text and captions first, then the Supplementary
   Materials in document order (Materials and Methods, Supplementary Methods, Supplementary Text, captions); a range
   "\\SF{a} to \\SF{b}" includes the figures between a and b in 976's canonical order, which must stay contiguous.
   Writes sm_numbers.tex (\\SF{key} -> S#, \\SMREFS) and sm_order.txt, and re-writes sm_captions.tex (976) in that order.
2  Main text: pdflatex, bibtex (science.bst), pdflatex x2.
3  Supplementary Materials: main-text reference numbers injected (sm_mainrefs.tex from main.aux); after bibtex the
   main-text references are removed from sm.bbl and the counter starts after them, so the Supplementary-only
   references are numbered N+1 ... (Science: references continue from the main text into the Supplementary Materials).
4  Checks against config journal_science (D145 limits): title characters, abstract words, words of main text +
   references + captions, figures, main-text references, British spellings left, first citations of Figs 1-5 and
   their panels, Supplementary figure ranges contiguous, data S citations in sequence, LaTeX errors and undefined
   references or citations.
Output (lib/io.write_csv): results/r10_science/science_checks.csv. PDFs: manuscript/science/build/{main,sm}.pdf.
Run: COCH_ROOT=/path/to/coch-rythum python scripts/977_science_manuscript.py
"""
import importlib.util
import os
import re
import subprocess
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib.io import CFG, ROOT, log, write_csv  # noqa: E402

SCI = ROOT / "manuscript" / "science"
BUILD = SCI / "build"
J = CFG["journal_science"]
ROWS = []
_spec = importlib.util.spec_from_file_location("s976", str(Path(__file__).resolve().parent / "976_science_convert.py"))
S976 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(S976)
CANON = list(S976.SF_FILES)                      # canonical order of the Supplementary figure keys (976)
SF_RE = re.compile(r"\\SF\{(\w+)\}(?:\s+to\s+\\SF\{(\w+)\})?")


def add(check, scope, value, limit, status, detail=""):
    ROWS.append(dict(check=check, scope=scope, value=value, limit=limit, status=status, detail=detail))
    log(f"{status:6s} {check:10s} {scope}: {value} (limit {limit}) {detail}")


def strip_comments(t):
    return "\n".join(re.sub(r"(?<!\\)%.*", "", ln) for ln in t.split("\n"))


def region(t, name):
    m = re.search(rf"% {name}:begin\n(.*?)% {name}:end", t, flags=re.S)
    return m.group(1) if m else ""


# ---------------------------------------------------------------------------------------------- 1 numbering
def sf_sequence(text):
    seq = []
    for m in SF_RE.finditer(strip_comments(text)):
        a, b = m.group(1), m.group(2)
        keys = [a]
        if b:
            i, j = CANON.index(a), CANON.index(b)
            keys = CANON[i:j + 1]
        seq += keys
    return seq


def numbering():
    order = []
    for _ in range(4):                                   # captions can add first citations; iterate to a fixed point
        texts = [(SCI / "main.tex").read_text(encoding="utf-8"), (SCI / "captions.tex").read_text(encoding="utf-8")]
        texts += [(SCI / f).read_text(encoding="utf-8") for f in ("sm_methods.tex", "sm_supmethods.tex", "sm_text.tex",
                                                                    "sm_captions.tex")]
        new = []
        for t in texts:
            for k in sf_sequence(t):
                if k not in new:
                    new.append(k)
        uncited = [k for k in CANON if k not in new]
        new += uncited
        if new == order:
            break
        order = new
        (SCI / "sm_order.txt").write_text(" ".join(order) + "\n", encoding="utf-8", newline="\n")
        (SCI / "sm_captions.tex").write_text("% GENERATED by scripts/977 via 976 captions() in the order of first "
                                             "citation; do not edit\n" + S976.captions(order), encoding="utf-8",
                                             newline="\n")
    add("numbering", "Supplementary figures", len(order), len(CANON), "pass" if len(order) == len(CANON) else "fail",
        " ".join(order))
    if uncited:
        add("numbering", "Supplementary figures never cited", len(uncited), 0, "warn", " ".join(uncited))
    return order


def write_numbers(order, smrefs="see the Supplementary Materials"):
    lines = ["% GENERATED by scripts/977_science_manuscript.py (order of first citation); do not edit", "\\makeatletter"]
    lines += [f"\\expandafter\\def\\csname sfn@{k}\\endcsname{{S{i}}}" for i, k in enumerate(order, 1)]
    lines += ["\\makeatother", f"\\def\\SMREFS{{{smrefs}}}"]
    (SCI / "sm_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


# ---------------------------------------------------------------------------------------------- 2-3 build
def env():
    e = os.environ.copy()
    e["PATH"] = os.pathsep.join(x for x in e["PATH"].split(os.pathsep) if "tensorflow_jni" not in x)
    e["BIBINPUTS"] = os.pathsep.join([str(SCI), str(ROOT / "manuscript"), ""])
    e["BSTINPUTS"] = os.pathsep.join([str(SCI), ""])
    e["TEXINPUTS"] = os.pathsep.join([str(SCI), ""])
    return e


def run(cmd):
    r = subprocess.run(cmd, cwd=SCI, env=env(), capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.returncode


def pdflatex(doc):
    return run(["pdflatex", "-no-shell-escape", "-interaction=nonstopmode", "-output-directory=build", f"{doc}.tex"])


def bibtex(doc):
    r = subprocess.run(["bibtex", doc], cwd=BUILD, env=env(), capture_output=True, text=True)
    return r.returncode


BIBCITE = re.compile(r"^\\bibcite\{([^}]*)\}.*$", re.M)


def build():
    BUILD.mkdir(exist_ok=True)
    pdflatex("main")
    bibtex("main")
    pdflatex("main")
    pdflatex("main")
    aux = (BUILD / "main.aux").read_text(encoding="utf-8", errors="replace")
    cites = BIBCITE.findall(aux)
    lines = [m.group(0) for m in BIBCITE.finditer(aux)]
    (SCI / "sm_mainrefs.tex").write_text("\\makeatletter\n" + "\n".join(lines) + "\n\\makeatother\n", encoding="utf-8",
                                         newline="\n")
    n_main = len(cites)
    pdflatex("sm")
    bibtex("sm")
    bbl = (BUILD / "sm.bbl").read_text(encoding="utf-8", errors="replace")
    head, rest = bbl.split("\\bibitem", 1)
    items = ["\\bibitem" + x for x in rest.split("\\bibitem")]
    items[-1] = items[-1].replace("\\end{thebibliography}", "").rstrip() + "\n"
    keep = [it for it in items if re.match(r"\\bibitem\{([^}]*)\}", it).group(1) not in set(cites)]
    head = re.sub(r"(\\begin\{thebibliography\}\{[^}]*\})", r"\1\n\\makeatletter\\setcounter{NAT@ctr}{" + str(n_main)
                  + r"}\\makeatother", head)
    (BUILD / "sm.bbl").write_text(head + "".join(keep) + "\n\\end{thebibliography}\n", encoding="utf-8", newline="\n")
    m_sm = len(keep)
    pdflatex("sm")
    pdflatex("sm")
    return n_main, m_sm


# ---------------------------------------------------------------------------------------------- 4 checks
def plain(t):
    t = strip_comments(t)
    t = re.sub(r"\\(cite|SF|label|ref|input|includegraphics|sciFig|smFig)\{[^}]*\}(\{[^}]*\})*", " ", t)
    t = re.sub(r"\\[A-Za-z]+\*?(\[[^\]]*\])?", " ", t)
    t = re.sub(r"[{}$~\\^_]", " ", t)
    return t


def words(t):
    return len([w for w in plain(t).split() if re.search(r"[A-Za-z0-9]", w)])


def bbl_words(path):
    t = Path(path).read_text(encoding="utf-8", errors="replace")
    t = t.split("\\providecommand{\\eprint}", 1)[-1]
    t = re.sub(r"\\bibitem\{[^}]*\}", " ", t)
    t = re.sub(r"\\bibinfo\{[^}]*\}", " ", t)
    t = t.replace("\\newblock", " ").replace("\\end{thebibliography}", " ")
    return words(t)


def checks(n_main, m_sm, order):
    main = (SCI / "main.tex").read_text(encoding="utf-8")
    cap = (SCI / "captions.tex").read_text(encoding="utf-8")
    title = re.search(r"\{\\Large\\textbf\{(.*?)\}\}", main, flags=re.S).group(1)
    title = " ".join(title.split())
    add("title", "characters", len(title), J["title_max_chars"], "pass" if len(title) <= J["title_max_chars"] else
        "fail", title)
    oss = re.search(r"One-sentence summary:\}(.*?)\n\n", main, flags=re.S).group(1)
    add("summary", "one-sentence summary characters", len(" ".join(plain(oss).split())), "", "report")
    wa = words(region(main, "abstract"))
    add("words", "abstract", wa, J["abstract_max_words"], "pass" if wa <= J["abstract_max_words"] else "fail")
    wm = words(region(main, "maintext"))
    wc = words(cap)
    wr = bbl_words(BUILD / "main.bbl")
    tot = wm + wc + wr
    add("words", "main text + references + captions", tot, J["total_words"], "pass" if tot <= J["total_words"] else
        "fail", f"main text {wm}; captions {wc}; references {wr}")
    nf = len(re.findall(r"\\figpage\{", strip_comments(main)))
    add("items", "figures", nf, J["figures_max"], "pass" if nf <= J["figures_max"] else "fail")
    add("refs", "main-text references", n_main, f"about {J['refs_main']}",
        "pass" if n_main <= J["refs_main"] + 8 else "warn", f"Supplementary-only references {m_sm}")
    # British spellings left (running text of every Science file)
    brit = {}
    for f in ["main.tex", "captions.tex", "sm.tex", "sm_methods.tex", "sm_supmethods.tex", "sm_text.tex",
              "sm_captions.tex", "sm_data.tex", "cover_letter.tex"]:
        if (SCI / f).exists():
            hits = S976._US_TEXT_RE.findall(strip_comments((SCI / f).read_text(encoding="utf-8")))
            hits = [h for h in hits if S976.US_TEXT[h.lower()] != h.lower()]
            if hits:
                brit[f] = sorted(set(hits))
    add("lint", "British spellings left", sum(len(v) for v in brit.values()), 0, "pass" if not brit else "fail",
        "; ".join(f"{k}: {' '.join(v)}" for k, v in brit.items()))
    # first citations of the main figures and their panels (main text)
    body = strip_comments(region(main, "maintext"))
    seen_f, seen_p = [], {}
    for m in re.finditer(r"Figs?\.~(\d)((?:[A-I]|,\s*[A-I](?:\s+(?:and|to)\s+[A-I])?)?)", body):
        f = int(m.group(1))
        if f not in seen_f:
            seen_f.append(f)
        g = m.group(2)
        rng = re.search(r"([A-I])\s+to\s+([A-I])", g)
        ps = [chr(c) for c in range(ord(rng.group(1)), ord(rng.group(2)) + 1)] if rng else re.findall(r"[A-I]", g)
        for p in ps:
            seen_p.setdefault(f, [])
            if p not in seen_p[f]:
                seen_p[f].append(p)
    add("order", "first citation of Figs", " ".join(map(str, seen_f)), "1 2 3 ...",
        "pass" if seen_f == sorted(seen_f) and seen_f == list(range(1, len(seen_f) + 1)) else "fail")
    for f, ps in sorted(seen_p.items()):
        add("order", f"Fig. {f} panels", "".join(ps), "alphabetical", "pass" if ps == sorted(ps) else "warn")
    # ranges of Supplementary figures contiguous in the final numbering
    num = {k: i for i, k in enumerate(order, 1)}
    bad = []
    for f in ["main.tex", "captions.tex", "sm_methods.tex", "sm_supmethods.tex", "sm_text.tex", "sm_captions.tex"]:
        for m in SF_RE.finditer(strip_comments((SCI / f).read_text(encoding="utf-8"))):
            if m.group(2):
                a, b = num[m.group(1)], num[m.group(2)]
                span = CANON[CANON.index(m.group(1)):CANON.index(m.group(2)) + 1]
                if sorted(num[k] for k in span) != list(range(a, b + 1)):
                    bad.append(f"{f}: {m.group(0)}")
    add("order", "Supplementary figure ranges contiguous", len(bad), 0, "pass" if not bad else "fail", "; ".join(bad))
    # data S: first citations in sequence through main text and Supplementary Materials
    seq = []
    for f in ["main.tex", "captions.tex", "sm_methods.tex", "sm_supmethods.tex", "sm_text.tex", "sm_captions.tex"]:
        for m in re.finditer(r"data~S(\d+)(?:\s+(?:to|and)\s+S(\d+))?", strip_comments((SCI / f).read_text(
                encoding="utf-8"))):
            a = int(m.group(1))
            b = int(m.group(2)) if m.group(2) else a
            for k in range(a, b + 1):
                if k not in seq:
                    seq.append(k)
    add("order", "first citation of data S", " ".join(map(str, seq)), "1 2 3 ...",
        "pass" if seq == list(range(1, len(seq) + 1)) else "warn")
    # every Supplementary figure on one page with its caption (the next caption, or the references, on the next page)
    import pymupdf
    sm = pymupdf.open(BUILD / "sm.pdf")
    heads = {}
    for i, pg in enumerate(sm):
        for m in re.finditer(r"Fig\. S(\d+)\. ", pg.get_text()):
            heads.setdefault(int(m.group(1)), i)
    refs = next(i for i, pg in enumerate(sm) if i > max(heads.values()) and re.search(r"^References$", pg.get_text(),
                                                                                       re.M))
    spill = [f"S{k}" for k in sorted(heads) if heads.get(k + 1, refs) != heads[k] + 1]
    add("pages", "Supplementary figures on one page with the caption", len(heads) - len(spill), len(heads),
        "pass" if not spill else "fail", " ".join(spill))
    # LaTeX problems
    for doc in ("main", "sm"):
        lg = (BUILD / f"{doc}.log").read_text(encoding="utf-8", errors="replace")
        errs = re.findall(r"^! .*$", lg, flags=re.M)
        und = sorted(set(re.findall(r"(?:Citation|Reference) `([^']+)' on page", lg)))
        add("build", f"{doc}.tex errors", len(errs), 0, "pass" if not errs else "fail", " | ".join(errs[:3]))
        add("build", f"{doc}.tex undefined citations or references", len(und), 0, "pass" if not und else "fail",
            " ".join(und[:10]))


def main():
    order = numbering()
    write_numbers(order)
    n_main, m_sm = build()
    write_numbers(order, f"{n_main + 1}--{n_main + m_sm}" if m_sm else "none")
    pdflatex("main")
    pdflatex("sm")
    checks(n_main, m_sm, order)
    df = pd.DataFrame(ROWS)
    write_csv(df, "r10_science", "science_checks.csv", "Science version (977, D144/D145): build and compliance checks "
              "of manuscript/science against the assumed Science Research Article limits (config journal_science)",
              required=["check", "scope", "value", "status"])
    log("summary: " + ", ".join(f"{k} {v}" for k, v in df.status.value_counts().items()))


if __name__ == "__main__":
    main()
